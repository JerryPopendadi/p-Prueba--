/** JSON data generated by thefaces/src/build.py. */
function tf_spa_data( $name ) {
	static $cache = array();
	if ( ! isset( $cache[ $name ] ) ) {
		$file           = TF_SPA_DIR . 'data/' . $name . '.json';
		$cache[ $name ] = file_exists( $file ) ? json_decode( file_get_contents( $file ), true ) : array();
	}
	return $cache[ $name ];
}

/**
 * Current language: shortcode attribute > Polylang > WPML > first URL segment (/ru/...) > default setting.
 */
function tf_spa_lang( $attr = '' ) {
	$langs = tf_spa_langs();
	if ( $attr && in_array( $attr, $langs, true ) ) {
		return $attr;
	}
	if ( is_singular() ) {
		$meta = get_post_meta( get_queried_object_id(), '_tf_lang', true );
		if ( $meta && in_array( $meta, $langs, true ) ) {
			return $meta;
		}
	}
	if ( function_exists( 'pll_current_language' ) ) {
		$l = pll_current_language( 'slug' );
		if ( in_array( $l, $langs, true ) ) {
			return $l;
		}
	}
	if ( defined( 'ICL_LANGUAGE_CODE' ) && in_array( ICL_LANGUAGE_CODE, $langs, true ) ) {
		return ICL_LANGUAGE_CODE;
	}
	$uri  = isset( $_SERVER['REQUEST_URI'] ) ? wp_unslash( $_SERVER['REQUEST_URI'] ) : '';
	$path = trim( (string) wp_parse_url( $uri, PHP_URL_PATH ), '/' );
	$base = trim( (string) wp_parse_url( home_url( '/' ), PHP_URL_PATH ), '/' );
	if ( $base && 0 === strpos( $path, $base ) ) {
		$path = trim( substr( $path, strlen( $base ) ), '/' );
	}
	$seg = explode( '/', $path );
	if ( isset( $seg[0] ) && in_array( $seg[0], $langs, true ) ) {
		return $seg[0];
	}
	$def = tf_spa_opt( 'default_lang' );
	return in_array( $def, $langs, true ) ? $def : 'en';
}

/** URL of a site page in a language: /ru/menu/ (English without prefix). */
function tf_spa_page_url( $slug, $lang ) {
	$prefix = ( 'en' === $lang || ! tf_spa_opt( 'lang_prefix' ) ) ? '' : $lang . '/';
	return home_url( '/' . $prefix . ( $slug && 'home' !== $slug ? $slug . '/' : '' ) );
}

/** Read one generated HTML file and fill in the plugin and site URLs. */
function tf_spa_file( $rel ) {
	$rel  = preg_replace( '/[^a-z0-9\/_-]/i', '', $rel );
	$file = TF_SPA_DIR . 'blocks/' . $rel . '.html';
	if ( ! file_exists( $file ) ) {
		return '';
	}
	$home = untrailingslashit( home_url() );
	if ( ! tf_spa_opt( 'lang_prefix' ) ) {
		// Sites without language folders: every language link points to the same addresses.
		$html = file_get_contents( $file );
		$html = preg_replace( '#\{\{TF_HOME\}\}/(ru|es|de|th|id|ja|fr|uk)/#', '{{TF_HOME}}/', $html );
	} else {
		$html = file_get_contents( $file );
	}
	return strtr(
		$html,
		array(
			'{{TF_ASSETS}}' => TF_SPA_URL . 'assets/media/',
			'{{TF_HOME}}'   => $home,
		)
	);
}

/** A whole page (home, menu, five-elements, ubud, sanur, founders, gift-certificates, partners, journal). */
function tf_spa_render_page( $key, $lang ) {
	$pages = tf_spa_data( 'pages' );
	if ( ! isset( $pages[ $key ] ) ) {
		return '<!-- THE FACES: unknown page "' . esc_html( $key ) . '" -->';
	}
	$out = '';
	foreach ( $pages[ $key ] as $block ) {
		if ( 'landing' === $block ) {
			$out .= tf_spa_file( "$lang/pages/$key-landing" );
		} elseif ( 0 === strpos( $block, 'salon-' ) ) {
			$out .= tf_spa_file( "$lang/pages/$key-salon" );
		} elseif ( '01-header' === $block ) {
			$out .= tf_spa_file( "$lang/pages/$key-01-header" );
			if ( 'home' !== $key && ! array_intersect( array( 'landing', '21-journal-all', 'salon-ubud', 'salon-sanur' ), $pages[ $key ] ) ) {
				$out .= tf_spa_file( "$lang/pages/$key-intro" );
			}
		} elseif ( '15-footer' === $block ) {
			$out .= tf_spa_file( "$lang/pages/$key-15-footer" );
		} else {
			$html = tf_spa_file( "$lang/$block" );
			if ( '14-faq' === $block && 'home' !== $key ) {
				// FAQ rich-result data only on the home page, so inner pages do not compete with it.
				$html = preg_replace( '#<script type="application/ld\+json">\{"@context": "https://schema.org", "@type": "FAQPage".*?</script>#s', '', $html );
			}
			if ( '13-journal' === $block ) {
				$html = tf_spa_dynamic_posts( $html, $lang, 3 );
			} elseif ( '21-journal-all' === $block ) {
				$html = tf_spa_journal_all( $html, $lang );
			}
			$out .= $html;
		}
	}
	return $out;
}

/** Is the current request a post shown with the THE FACES template (the journal articles)? */
function tf_spa_is_post() {
	return is_singular( 'post' ) && 'thefaces-canvas' === get_page_template_slug( get_queried_object_id() );
}

/** Image of a journal post: plugin image, featured image or a default. */
function tf_spa_post_image( $post_id ) {
	$img = get_post_meta( $post_id, '_tf_img', true );
	if ( $img ) {
		return TF_SPA_URL . 'assets/media/' . $img;
	}
	$thumb = get_the_post_thumbnail_url( $post_id, 'large' );
	return $thumb ? $thumb : TF_SPA_URL . 'assets/media/g04-interior.webp';
}

/** Posts of one language: posts marked with that language; unmarked posts count as the default language. */
function tf_spa_lang_posts( $lang, $limit ) {
	$meta = array( array( 'key' => '_tf_lang', 'value' => $lang ) );
	if ( tf_spa_opt( 'default_lang' ) === $lang ) {
		$meta = array( 'relation' => 'OR', $meta[0], array( 'key' => '_tf_lang', 'compare' => 'NOT EXISTS' ) );
	}
	return get_posts( array( 'post_type' => 'post', 'post_status' => 'publish', 'numberposts' => $limit, 'meta_query' => $meta ) );
}

/** Replace the example cards of the Journal block with the real posts of that language. */
function tf_spa_dynamic_posts( $html, $lang, $limit ) {
	$posts = tf_spa_lang_posts( $lang, $limit );
	if ( ! $posts ) {
		return $html;
	}
	$cards = '';
	foreach ( $posts as $p ) {
		$cards .= tf_spa_card( $p, $lang );
	}
	return preg_replace( '#<!--tf-posts-->.*?<!--/tf-posts-->#s', '<!--tf-posts-->' . $cards . '<!--/tf-posts-->', $html );
}

/** Category key and name of a post (plugin meta, or its first WordPress category). */
function tf_spa_post_cat( $post_id, $lang ) {
	$key = get_post_meta( $post_id, '_tf_catkey', true );
	if ( $key ) {
		$names = tf_spa_data( 'jocats' );
		return array( $key, isset( $names[ $lang ][ $key ] ) ? $names[ $lang ][ $key ] : $key );
	}
	$cats = get_the_category( $post_id );
	foreach ( (array) $cats as $c ) {
		if ( 'uncategorized' === $c->slug ) {
			continue;
		}
		if ( preg_match( '/^(face|head|rituals|elements|story|news)(-[a-z]{2})?$/', $c->slug, $m ) ) {
			return array( $m[1], $c->name );
		}
		return array( 'wp-' . $c->slug, $c->name );
	}
	return array( '', '' );
}

/** Journal page: every post of the language, with category chips and search data. */
function tf_spa_journal_all( $html, $lang ) {
	$posts = tf_spa_lang_posts( $lang, 200 );
	if ( ! $posts ) {
		return $html;
	}
	$cards = '';
	$chips = array();
	$count = array();
	foreach ( $posts as $i => $p ) {
		list( $ck, $cn ) = tf_spa_post_cat( $p->ID, $lang );
		if ( $ck ) {
			$chips[ $ck ] = $cn;
			$count[ $ck ] = isset( $count[ $ck ] ) ? $count[ $ck ] + 1 : 1;
		}
		$cards .= tf_spa_card( $p, $lang, 0 === $i );
	}
	$html = preg_replace( '#<!--tf-posts-all-->.*?<!--/tf-posts-all-->#s', '<!--tf-posts-all-->' . $cards . '<!--/tf-posts-all-->', $html );
	$label = '';
	if ( preg_match( '#<!--tf-chips--><button[^>]*>(.*?)<span>#s', $html, $m ) ) {
		$label = trim( $m[1] );
	}
	$btn   = '<button type="button" class="on" data-jcat="">' . esc_html( $label ) . ' <span>' . count( $posts ) . '</span></button>';
	$order = array( 'face', 'head', 'rituals', 'elements', 'story', 'news' );
	uksort(
		$chips,
		function ( $a, $b ) use ( $order ) {
			$x = array_search( $a, $order, true );
			$y = array_search( $b, $order, true );
			return ( false === $x ? 99 : $x ) - ( false === $y ? 99 : $y );
		}
	);
	foreach ( $chips as $k => $n ) {
		$btn .= '<button type="button" data-jcat="' . esc_attr( $k ) . '">' . esc_html( $n ) . ' <span>' . (int) $count[ $k ] . '</span></button>';
	}
	return preg_replace( '#<!--tf-chips-->.*?<!--/tf-chips-->#s', '<!--tf-chips-->' . $btn . '<!--/tf-chips-->', $html );
}

/** Reading time of a post in minutes. */
function tf_spa_read_min( $p, $lang ) {
	$text = wp_strip_all_tags( $p->post_content );
	$n    = in_array( $lang, array( 'ja', 'th' ), true ) ? mb_strlen( $text ) / 450 : str_word_count( $text ) / 200;
	if ( ! in_array( $lang, array( 'ja', 'th' ), true ) && $n < 1 ) {
		$n = count( preg_split( '/\s+/u', trim( $text ) ) ) / 200;
	}
	return max( 2, (int) round( $n ) );
}

/** One article card (same markup as the generated blocks). */
function tf_spa_card( $p, $lang, $featured = false ) {
	list( $ck, $cn ) = tf_spa_post_cat( $p->ID, $lang );
	$title = get_the_title( $p );
	$ex    = get_the_excerpt( $p );
	$tpl   = tf_spa_data( 'readmin' );
	$read  = isset( $tpl[ $lang ] ) ? str_replace( '{n}', tf_spa_read_min( $p, $lang ), $tpl[ $lang ] ) : get_the_date( 'd.m.Y', $p );
	return '<a class="post' . ( $featured ? ' featured' : '' ) . '" data-cat="' . esc_attr( $ck ) . '" data-text="' . esc_attr( mb_strtolower( $title . ' ' . $ex . ' ' . $cn ) ) . '" href="' . esc_url( get_permalink( $p ) ) . '">'
		. '<div class="ph"><img src="' . esc_url( tf_spa_post_image( $p->ID ) ) . '" alt="" loading="lazy"></div><div class="tx">'
		. '<p class="d">' . ( $cn ? '<span class="cat-tag">' . esc_html( $cn ) . '</span> ' : '' ) . esc_html( $read ) . '</p>'
		. '<h3>' . esc_html( $title ) . '</h3><p class="ex">' . esc_html( $ex ) . '</p></div></a>';
}

/** Up to 3 related posts: same category first, then the latest of the language. */
function tf_spa_related( $post, $lang ) {
	list( $ck ) = tf_spa_post_cat( $post->ID, $lang );
	$all  = tf_spa_lang_posts( $lang, 60 );
	$same = array();
	$rest = array();
	foreach ( $all as $p ) {
		if ( $p->ID === $post->ID ) {
			continue;
		}
		list( $k ) = tf_spa_post_cat( $p->ID, $lang );
		if ( $k && $k === $ck ) {
			$same[] = $p;
		} else {
			$rest[] = $p;
		}
	}
	$out = '';
	foreach ( array_slice( array_merge( $same, $rest ), 0, 3 ) as $p ) {
		$out .= tf_spa_card( $p, $lang );
	}
	return $out;
}

/** Permalinks of the same article in every language (posts share the _tf_group meta). */
function tf_spa_translations( $post_id ) {
	$group = get_post_meta( $post_id, '_tf_group', true );
	$out   = array();
	if ( ! $group ) {
		return $out;
	}
	$sib = get_posts( array( 'post_type' => 'post', 'post_status' => 'publish', 'numberposts' => 20, 'meta_key' => '_tf_group', 'meta_value' => $group ) );
	foreach ( $sib as $p ) {
		$l = get_post_meta( $p->ID, '_tf_lang', true );
		if ( $l ) {
			$out[ $l ] = get_permalink( $p );
		}
	}
	return $out;
}

/** Point the language switcher of header/footer to the translations of the article. */
function tf_spa_patch_lang_links( $html, $post_id ) {
	foreach ( tf_spa_translations( $post_id ) as $l => $url ) {
		$html = preg_replace( '#href="[^"]*"(\s+hreflang="' . preg_quote( $l, '#' ) . '")#', 'href="' . esc_url( $url ) . '"$1', $html );
	}
	return $html;
}

/** Record of a generated journal article (from data/posts.json) for a post, or null. */
function tf_spa_article( $post_id ) {
	$group = get_post_meta( $post_id, '_tf_group', true );
	if ( ! $group ) {
		return null;
	}
	foreach ( (array) tf_spa_data( 'posts' ) as $a ) {
		if ( isset( $a['id'] ) && $a['id'] === $group ) {
			return $a;
		}
	}
	return null;
}

/** URL of one of the plugin's pages in a language (the real page when it exists). */
function tf_spa_key_url( $key, $lang ) {
	$map = get_option( 'thefaces_spa_pages', array() );
	if ( isset( $map[ $lang ][ $key ] ) && get_post( $map[ $lang ][ $key ] ) ) {
		return get_permalink( $map[ $lang ][ $key ] );
	}
	return tf_spa_page_url( $key, $lang );
}

/**
 * Canonical URL of a journal article. Articles that retell a main page (five elements, founders,
 * gift certificates, partners) point to that page, so the two never compete in Google.
 */
function tf_spa_post_canonical( $post_id ) {
	$a = tf_spa_article( $post_id );
	if ( ! $a || empty( $a['canonical'] ) ) {
		return '';
	}
	$lang = get_post_meta( $post_id, '_tf_lang', true );
	return tf_spa_key_url( $a['canonical'], $lang ? $lang : 'en' );
}

function tf_spa_filter_canonical( $url ) {
	if ( is_singular( 'post' ) ) {
		$c = tf_spa_post_canonical( get_queried_object_id() );
		if ( $c ) {
			return $c;
		}
	}
	return $url;
}
add_filter( 'wpseo_canonical', 'tf_spa_filter_canonical', 20 );
add_filter( 'get_canonical_url', 'tf_spa_filter_canonical', 20 );

/** A journal article with the site header, article layout, booking box and footer. */
function tf_spa_render_post( $post ) {
	$lang  = get_post_meta( $post->ID, '_tf_lang', true );
	$lang  = $lang ? $lang : tf_spa_lang();
	$cat   = get_post_meta( $post->ID, '_tf_cat', true );
	$shell = tf_spa_file( "$lang/post-shell" );
	$art       = tf_spa_article( $post->ID );
	$svc       = $art && ! empty( $art['service'] ) ? $art['service'] : 'menu';
	$svc_url   = tf_spa_key_url( $svc, $lang );
	$svc_label = $art && isset( $art['service_label'][ $lang ] ) ? $art['service_label'][ $lang ] : '';
	$body  = strtr(
		$shell,
		array(
			'{{POST_TITLE}}'   => esc_html( get_the_title( $post ) ),
			'{{POST_CAT}}'     => esc_html( $cat ),
			'{{POST_EXCERPT}}' => esc_html( get_the_excerpt( $post ) ),
			'{{POST_IMG}}'     => esc_url( tf_spa_post_image( $post->ID ) ),
			'{{POST_DATE}}'    => esc_html( get_the_date( 'd.m.Y', $post ) ),
			'{{POST_CONTENT}}' => apply_filters( 'the_content', $post->post_content ),
			'{{POST_SVC_URL}}'   => esc_url( $svc_url ),
			'{{POST_SVC_LABEL}}' => esc_html( $svc_label ),
		)
	);
	$body  = preg_replace( '#<!--tf-related-->.*?<!--/tf-related-->#s', '<!--tf-related-->' . tf_spa_related( $post, $lang ) . '<!--/tf-related-->', $body );
	return tf_spa_patch_lang_links( tf_spa_file( "$lang/pages/journal-01-header" ), $post->ID ) . $body
		. tf_spa_patch_lang_links( tf_spa_file( "$lang/pages/journal-15-footer" ), $post->ID );
}

/**
 * [thefaces page="home"]            whole page in the current language
 * [thefaces block="senses"]         one section (header, hero, philosophy, senses, elements, signatures,
 *                                   menu-builder, gallery, salons, founders, gifts, partners, journal, faq, footer, waterfall)
 * [thefaces page="menu" lang="ru"]  force a language
 */
function tf_spa_shortcode( $atts ) {
	$atts = shortcode_atts( array( 'page' => '', 'block' => '', 'lang' => '' ), $atts, 'thefaces' );
	$lang = tf_spa_lang( $atts['lang'] );
	if ( '' !== $atts['block'] ) {
		$map  = tf_spa_data( 'blocks' );
		$name = isset( $map[ $atts['block'] ] ) ? $map[ $atts['block'] ] : '';
		if ( ! $name ) {
			return '<!-- THE FACES: unknown block -->';
		}
		$html = tf_spa_file( "$lang/$name" );
		if ( '13-journal' === $name ) {
			return tf_spa_dynamic_posts( $html, $lang, 3 );
		}
		return '21-journal-all' === $name ? tf_spa_journal_all( $html, $lang ) : $html;
	}
	$key = ( '' === $atts['page'] ) ? 'home' : sanitize_title( $atts['page'] );
	return tf_spa_render_page( $key, $lang );
}
add_shortcode( 'thefaces', 'tf_spa_shortcode' );

/** Attributes of the [thefaces page="…"] shortcode on the current page, or null. */
function tf_spa_current_page() {
	static $found = false;
	if ( false !== $found ) {
		return $found;
	}
	$found = null;
	if ( is_singular() ) {
		$post = get_post();
		if ( $post && has_shortcode( $post->post_content, 'thefaces' ) ) {
			$found = array( 'page' => '', 'lang' => '', 'full' => false );
			if ( preg_match( '/' . get_shortcode_regex( array( 'thefaces' ) ) . '/s', $post->post_content, $m ) ) {
				$a = shortcode_parse_atts( $m[3] );
				if ( is_array( $a ) ) {
					$found['page'] = isset( $a['page'] ) ? sanitize_title( $a['page'] ) : '';
					$found['full'] = ! isset( $a['block'] );
					$found['lang'] = isset( $a['lang'] ) ? $a['lang'] : '';
				}
			}
		}
	}
	return $found;
}

