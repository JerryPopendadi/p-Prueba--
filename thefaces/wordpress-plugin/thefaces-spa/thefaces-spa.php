/** Languages, in the order used by the site. */
function tf_spa_langs() {
	return array( 'en', 'ru', 'es', 'de', 'th', 'id', 'ja', 'fr', 'uk' );
}

/** Plugin settings with defaults. */
function tf_spa_opt( $key ) {
	$defaults = array(
		'gtm'            => '',
		'default_lang'   => 'en',
		'seo'            => 1,
		'load_always'    => 0,
		'lang_prefix'    => 1,
		'security'       => 1,
		'xmlrpc_off'     => 1,
	);
	$opts = get_option( 'thefaces_spa', array() );
	return isset( $opts[ $key ] ) ? $opts[ $key ] : $defaults[ $key ];
}

