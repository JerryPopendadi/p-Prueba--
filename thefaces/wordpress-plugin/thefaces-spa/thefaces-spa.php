/**
 * Creates the 9 pages x 9 languages (and the journal posts) with their shortcode and the full-width template,
 * makes the English home the front page and turns on pretty permalinks. Existing pages are reused.
 *
 * @return array Number of pages created and reused.
 */
function tf_spa_setup_pages() {
	$pages   = array_keys( tf_spa_data( 'pages' ) );
	$seo     = tf_spa_data( 'seo' );
	$names   = tf_spa_data( 'langs' );
	$created = 0;
	$reused  = 0;
	$map     = array();

	if ( '' === get_option( 'permalink_structure' ) ) {
		update_option( 'permalink_structure', '/%postname%/' );
	}

	foreach ( tf_spa_langs() as $lang ) {
		$parent = 0;
		foreach ( array_merge( array( 'home' ), array_diff( $pages, array( 'home' ) ) ) as $key ) {
			$title = isset( $seo[ $lang ][ $key ]['title'] ) ? preg_split( '/\s*[·｜|]\s*/u', $seo[ $lang ][ $key ]['title'] )[0] : $key;
			if ( 'home' === $key ) {
				$slug  = ( 'en' === $lang ) ? 'home' : $lang;
				$title = 'THE FACES · ' . $names[ $lang ];
				$path  = $slug;
				$p_id  = 0;
			} else {
				$slug = $key;
				$path = ( 'en' === $lang ) ? $key : $lang . '/' . $key;
				$p_id = ( 'en' === $lang ) ? 0 : $parent;
			}
			$content  = '[thefaces page="' . $key . '" lang="' . $lang . '"]';
			$existing = get_page_by_path( $path, OBJECT, 'page' );
			if ( $existing ) {
				$id = $existing->ID;
				if ( false === strpos( $existing->post_content, '[thefaces' ) ) {
					wp_update_post( array( 'ID' => $id, 'post_content' => $content ) );
				}
				if ( 'publish' !== $existing->post_status ) {
					wp_update_post( array( 'ID' => $id, 'post_status' => 'publish' ) );
				}
				$reused++;
			} else {
				$id = wp_insert_post(
					array(
						'post_type'    => 'page',
						'post_status'  => 'publish',
						'post_title'   => $title,
						'post_name'    => $slug,
						'post_parent'  => $p_id,
						'post_content' => $content,
					)
				);
				if ( is_wp_error( $id ) || ! $id ) {
					continue;
				}
				$created++;
			}
			update_post_meta( $id, '_wp_page_template', 'thefaces-canvas' );
			if ( 'home' === $key ) {
				$parent = $id;
			}
			$map[ $lang ][ $key ] = $id;
		}
	}

	// Journal articles in every language (the first article of the list is the newest, so it is featured).
	$base = time();
	foreach ( tf_spa_data( 'posts' ) as $idx => $p ) {
		$date = gmdate( 'Y-m-d H:i:s', $base - $idx * 3600 );
		foreach ( tf_spa_langs() as $lang ) {
			if ( ! isset( $p['slug'][ $lang ] ) ) {
				continue;
			}
			$existing = get_page_by_path( $p['slug'][ $lang ], OBJECT, 'post' );
			if ( $existing ) {
				$id = $existing->ID;
				$reused++;
			} else {
				$id = wp_insert_post(
					array(
						'post_type'    => 'post',
						'post_status'  => 'publish',
						'post_title'   => $p['title'][ $lang ],
						'post_name'    => $p['slug'][ $lang ],
						'post_excerpt' => $p['excerpt'][ $lang ],
						'post_content' => $p['html'][ $lang ],
					)
				);
				if ( is_wp_error( $id ) || ! $id ) {
					continue;
				}
				$created++;
			}
			wp_update_post( array( 'ID' => $id, 'post_date_gmt' => $date, 'post_date' => get_date_from_gmt( $date ) ) );
			update_post_meta( $id, '_tf_lang', $lang );
			update_post_meta( $id, '_tf_group', $p['id'] );
			update_post_meta( $id, '_tf_img', $p['img'] );
			update_post_meta( $id, '_tf_cat', $p['cat'][ $lang ] );
			update_post_meta( $id, '_tf_catkey', $p['catkey'] );
			$term_slug = 'en' === $lang ? $p['catkey'] : $p['catkey'] . '-' . $lang;
			$term      = get_term_by( 'slug', $term_slug, 'category' );
			if ( ! $term ) {
				$t    = wp_insert_term( $p['catname'][ $lang ] . ( 'en' === $lang ? '' : ' (' . strtoupper( $lang ) . ')' ), 'category', array( 'slug' => $term_slug ) );
				$term = is_wp_error( $t ) ? null : get_term( $t['term_id'], 'category' );
			}
			if ( $term ) {
				wp_set_post_categories( $id, array( $term->term_id ), false );
			}
			update_post_meta( $id, '_wp_page_template', 'thefaces-canvas' );
		}
	}
	// The WordPress sample content is not part of the site.
	foreach ( array( 'hello-world' => 'post', 'sample-page' => 'page' ) as $slug => $type ) {
		$sample = get_page_by_path( $slug, OBJECT, $type );
		if ( $sample && 'publish' === $sample->post_status ) {
			wp_update_post( array( 'ID' => $sample->ID, 'post_status' => 'draft' ) );
		}
	}

	if ( isset( $map['en']['home'] ) ) {
		update_option( 'show_on_front', 'page' );
		update_option( 'page_on_front', $map['en']['home'] );
	}
	update_option( 'thefaces_spa_pages', $map, false );
	tf_spa_fill_yoast();
	flush_rewrite_rules();
	return array( 'created' => $created, 'reused' => $reused );
}

