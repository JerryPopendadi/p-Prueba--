/** True when another SEO plugin already writes titles and descriptions. */
function tf_spa_other_seo() {
	return defined( 'WPSEO_VERSION' ) || defined( 'RANK_MATH_VERSION' ) || defined( 'AIOSEO_VERSION' ) || defined( 'SEOPRESS_VERSION' ) || class_exists( 'The_SEO_Framework\Load' );
}

/** Title per page and language (from data/seo.json). */
function tf_spa_title( $title ) {
	$p = tf_spa_current_page();
	if ( ! $p || empty( $p['full'] ) || ! tf_spa_opt( 'seo' ) || tf_spa_other_seo() ) {
		return $title;
	}
	$seo  = tf_spa_data( 'seo' );
	$lang = tf_spa_lang( $p['lang'] );
	$key  = $p['page'] ? $p['page'] : 'home';
	return isset( $seo[ $lang ][ $key ]['title'] ) ? $seo[ $lang ][ $key ]['title'] : $title;
}
add_filter( 'pre_get_document_title', 'tf_spa_title', 20 );

/** Description, Open Graph and hreflang. */
function tf_spa_head_seo() {
	$p = tf_spa_current_page();
	if ( ! $p || empty( $p['full'] ) || ! tf_spa_opt( 'seo' ) ) {
		return;
	}
	$seo  = tf_spa_data( 'seo' );
	$lang = tf_spa_lang( $p['lang'] );
	$key  = $p['page'] ? $p['page'] : 'home';
	if ( ! isset( $seo[ $lang ][ $key ] ) ) {
		return;
	}
	$locales = array( 'en' => 'en_US', 'ru' => 'ru_RU', 'es' => 'es_ES', 'de' => 'de_DE', 'th' => 'th_TH', 'id' => 'id_ID', 'ja' => 'ja_JP' );
	if ( ! tf_spa_other_seo() ) {
		$t = $seo[ $lang ][ $key ]['title'];
		$d = $seo[ $lang ][ $key ]['desc'];
		echo '<meta name="description" content="' . esc_attr( $d ) . '">' . "\n";
		echo '<meta property="og:title" content="' . esc_attr( $t ) . '">' . "\n";
		echo '<meta property="og:description" content="' . esc_attr( $d ) . '">' . "\n";
		echo '<meta property="og:type" content="website">' . "\n";
		echo '<meta property="og:url" content="' . esc_url( tf_spa_page_url( $key, $lang ) ) . '">' . "\n";
		echo '<meta property="og:image" content="' . esc_url( TF_SPA_URL . 'assets/media/og-1200x630.jpg' ) . '">' . "\n";
		echo '<meta property="og:locale" content="' . esc_attr( $locales[ $lang ] ) . '">' . "\n";
		echo '<meta name="twitter:card" content="summary_large_image">' . "\n";
	}
	// Polylang and WPML write hreflang themselves.
	if ( tf_spa_opt( 'lang_prefix' ) && ! function_exists( 'pll_current_language' ) && ! defined( 'ICL_LANGUAGE_CODE' ) ) {
		foreach ( tf_spa_langs() as $l ) {
			echo '<link rel="alternate" hreflang="' . esc_attr( $l ) . '" href="' . esc_url( tf_spa_page_url( $key, $l ) ) . '">' . "\n";
		}
		echo '<link rel="alternate" hreflang="x-default" href="' . esc_url( tf_spa_page_url( $key, 'en' ) ) . '">' . "\n";
	}
}
add_action( 'wp_head', 'tf_spa_head_seo', 2 );

/** <html lang> follows the page language when no language plugin is active. */
function tf_spa_language_attributes( $output ) {
	$p = tf_spa_current_page();
	if ( $p && ! empty( $p['full'] ) && ! function_exists( 'pll_current_language' ) && ! defined( 'ICL_LANGUAGE_CODE' ) ) {
		return preg_replace( '/lang="[^"]*"/', 'lang="' . esc_attr( tf_spa_lang( $p['lang'] ) ) . '"', $output );
	}
	return $output;
}
add_filter( 'language_attributes', 'tf_spa_language_attributes' );

